#!/usr/bin/env python3
"""Rasterise the UI fonts into anti-aliased alpha glyph atlases (kernel/fontdata.h).

The generated header is committed, so building StreakOS does not need Python or
the fonts installed. Re-run only to change fonts or sizes:
    python3 tools/genfont.py > kernel/fontdata.h
"""
import sys
from PIL import Image, ImageDraw, ImageFont

INTER = "/usr/share/fonts/opentype/inter/"
JBM = "/usr/share/fonts/truetype/jetbrains-mono/"
FONTS = [
    ("ui", INTER + "Inter-Regular.otf", 15),
    ("bold", INTER + "Inter-SemiBold.otf", 15),
    ("small", INTER + "Inter-Regular.otf", 12),
    ("title", INTER + "InterDisplay-SemiBold.otf", 22),
    ("big", INTER + "InterDisplay-Light.otf", 44),
    ("mono", JBM + "JetBrainsMono-Regular.ttf", 14),
]

out = sys.stdout
out.write("/* Generated by tools/genfont.py - do not edit.\n"
          " * Inter and JetBrains Mono are licensed under the SIL Open Font License 1.1. */\n")
out.write("#pragma once\n#include \"font.h\"\n\n")
for name, path, size in FONTS:
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    data = bytearray()
    glyphs = []
    for c in range(32, 127):
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        img = Image.new("L", (size * 3, ascent + descent + 8), 0)
        ImageDraw.Draw(img).text((size, 4), ch, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((0, 0, 0, 0, adv, 0))
            continue
        x0, y0, x1, y1 = bbox
        crop = img.crop(bbox)
        off = len(data)
        data.extend(crop.tobytes())
        glyphs.append((x0 - size, y0 - 4, x1 - x0, y1 - y0, adv, off))
    out.write(f"static const unsigned char font_{name}_bits[{max(len(data),1)}] = {{\n")
    for i in range(0, len(data), 24):
        out.write("  " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
    out.write("};\n")
    out.write(f"static const glyph_t font_{name}_glyphs[95] = {{\n")
    for g in glyphs:
        out.write("  {%d,%d,%d,%d,%d,%d},\n" % g)
    out.write("};\n")
    out.write(f"const font_t font_{name} = {{ {ascent + descent}, {ascent}, font_{name}_glyphs, font_{name}_bits }};\n\n")
