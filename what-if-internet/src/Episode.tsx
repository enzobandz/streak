import React from 'react';
import {AbsoluteFill, Audio, interpolate, Sequence, staticFile, useCurrentFrame, useVideoConfig} from 'remotion';
import {SceneProvider, SceneT, TIMELINE, useScene} from './lib/timeline';
import {ChapterCard, ClockHUD, Finish, SourceTag, Wipe} from './components/ui/Overlays';
import {Sfx} from './audio/Sfx';
import {prog} from './lib/anim';
import {C} from './theme';
import {SCENE_COMPONENTS} from './scenes';
import {loadFonts} from './fonts';

loadFonts();

const ClockLayer: React.FC<{prev: number}> = ({prev}) => {
  const s = useScene();
  const f = useCurrentFrame();
  if (s.clock === null || s.clock === undefined) return null;
  const vis = Math.min(prog(f, 8, 26), 1 - prog(f, s.duration - 14, s.duration));
  return <ClockHUD hour={s.clock} prevHour={prev} visible={vis} />;
};

/** Chapter cards, clock and citations that sit above every scene. */
const SceneChrome: React.FC<{prevClock: number}> = ({prevClock}) => {
  const s = useScene();
  return (
    <>
      <ClockLayer prev={prevClock} />
      {s.chapter ? (
        <Sequence from={6} durationInFrames={130} layout="none">
          <ChapterCard title={s.chapter} />
        </Sequence>
      ) : null}
      {s.lines
        .filter((l) => l.source)
        .map((l) => (
          <Sequence key={l.id} from={l.from} durationInFrames={l.duration + 20} layout="none">
            <SourceTag text={l.source!} dur={l.duration + 20} />
          </Sequence>
        ))}
    </>
  );
};

export const Episode: React.FC<{sceneIds?: string[]; fadeOut?: boolean}> = ({sceneIds, fadeOut}) => {
  const {durationInFrames} = useVideoConfig();
  const frame = useCurrentFrame();
  const scenes: SceneT[] = sceneIds ? TIMELINE.scenes.filter((s) => sceneIds.includes(s.id)) : TIMELINE.scenes;
  const offset = scenes[0].from;
  let lastClock = 0;
  return (
    <AbsoluteFill style={{background: C.night}}>
      {scenes.map((sc, i) => {
        const Comp = SCENE_COMPONENTS[sc.id];
        const prevClock = lastClock;
        if (sc.clock !== null && sc.clock !== undefined) lastClock = sc.clock;
        return (
          <Sequence key={sc.id} from={sc.from - offset} durationInFrames={sc.duration} name={`scene:${sc.id}`}>
            <SceneProvider scene={sc}>
              <Comp />
              <SceneChrome prevClock={prevClock} />
            </SceneProvider>
          </Sequence>
        );
      })}
      {/* transitions between scenes */}
      {scenes.slice(1).map((sc) =>
        sc.id === 'title' ? null : (
          <Sequence key={'w' + sc.id} from={sc.from - offset - 12} durationInFrames={24} name="wipe">
            <Wipe len={24} />
            <Sfx name="whoosh" at={0} volume={0.35} />
          </Sequence>
        ),
      )}
      {/* narration */}
      {scenes.flatMap((sc) =>
        sc.lines.map((l) => (
          <Sequence key={l.id} from={sc.from - offset + l.from} durationInFrames={l.duration + 5} name={`vo:${l.id}`} layout="none">
            <Audio src={staticFile(`vo/${l.id}.mp3`)} volume={1} />
          </Sequence>
        )),
      )}
      {/* score (generated by tools/audio.py, already ducked under narration) */}
      <Audio
        src={staticFile('music/score.mp3')}
        trimBefore={offset}
        volume={(f) => 0.62 * (fadeOut ? interpolate(f, [durationInFrames - 30, durationInFrames], [1, 0], {extrapolateLeft: 'clamp', extrapolateRight: 'clamp'}) : 1)}
      />
      <Finish />
      {fadeOut ? (
        <AbsoluteFill style={{background: '#000', opacity: interpolate(frame, [durationInFrames - 20, durationInFrames], [0, 1], {extrapolateLeft: 'clamp'})}} />
      ) : null}
    </AbsoluteFill>
  );
};
